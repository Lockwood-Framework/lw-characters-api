local DB      = exports['lw-db']:DB()
local LWUtils = exports['lw-shared']:GetUtils()

-- ---------------------------------------------------------------------------
-- Internal helpers
-- ---------------------------------------------------------------------------

---@param  stateId  string
---@return          table|nil
local function FetchCharacter(stateId)
    return DB.single(
        'SELECT * FROM `lw_characters` WHERE `state_id` = ?',
        { stateId }
    )
end

-- ---------------------------------------------------------------------------
-- Module-level functions
-- Accessible to other server scripts in this resource (main.lua).
-- ---------------------------------------------------------------------------

--- Writes the character's last known position to the database.
--- Called by the periodic save loop and on character unload.
--- Must be called from within a Citizen.CreateThread.
---@param  stateId  string
---@param  coords   vector3
---@param  heading  number
function SaveLocation(stateId, coords, heading)
    DB.update([[
        UPDATE `lw_characters`
        SET    `last_x` = ?, `last_y` = ?, `last_z` = ?, `last_heading` = ?
        WHERE  `state_id` = ?
    ]], { coords.x, coords.y, coords.z, heading, stateId })
end

-- ---------------------------------------------------------------------------
-- Export implementations
